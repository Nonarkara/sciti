// Writes public/_redirects for the Cloudflare Pages project smart-city-thailand-index.
// Plain rules come first. They count toward the 2,000 static cap.
// Wildcards come last. They count toward the 100 dynamic cap.
// A rule with status 404 is not written. Unknown paths fall through to 404.html.
// An app route is `/path / 200`, which serves the root index. It is not `/index.html`.

import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { PROVINCE_ALIASES } from "../src/lib/legacy.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const redirects = JSON.parse(readFileSync(path.join(root, "src/data/redirects.json"), "utf8"));
const baseline = JSON.parse(readFileSync(path.join(root, "public/data/baseline.json"), "utf8"));
const byName = new Map(baseline.places.map((place) => [place.en.toLowerCase(), place.id]));

function rule(from, to, status) {
  return `${from}   ${to}   ${status}`;
}

function isFile(pathname) {
  return /\.[a-z0-9]+$/i.test(pathname.split("/").pop() || "");
}

const staticRules = [];
const dynamicRules = [];

function addStatic(from, to, status) {
  staticRules.push(rule(from, to, status));
  if (!from.endsWith("/") && !isFile(from)) staticRules.push(rule(`${from}/`, to, status));
}

function addDynamic(from, to, status) {
  dynamicRules.push(rule(from, to, status));
}

const toAbout = [
  "/creative-economy",
  "/bingo",
  "/partners",
  "/audit",
  "/asus",
  "/why",
  "/showcase",
  "/invest",
  "/program",
  "/knowledge",
  "/Kimi",
  "/kimi",
];
for (const from of toAbout) addStatic(from, "/about", 302);

for (const from of ["/rankings", "/discover", "/story", "/map", "/sitemap.xml"]) {
  if (isFile(from)) staticRules.push(rule(from, "/", 302));
  else addStatic(from, "/", 302);
}

for (const from of ["/methodology", "/sources", "/references"]) addStatic(from, "/methods", 302);

staticRules.push(rule("/data/cities.json", "/data/baseline.json", 302));
staticRules.push(rule("/downloads/SCITI-2026-cities-dataset.csv", "/data/baseline.csv", 302));

const slugs = Object.keys(redirects).sort();
for (const slug of slugs) {
  const key = String(redirects[slug]).toLowerCase();
  const id = byName.get(PROVINCE_ALIASES[key] || key);
  if (!id) throw new Error(`no province id for ${slug} → ${redirects[slug]}`);
  addStatic(`/city/${slug}`, `/place/${id}`, 302);
  addStatic(`/canvas/${slug}`, `/place/${id}`, 302);
}

for (const from of ["/about", "/compare", "/coverage", "/methods"]) addStatic(from, "/", 200);

addDynamic("/city/*", "/", 302);
addDynamic("/canvas/*", "/", 302);
addDynamic("/methods/*", "/", 200);
addDynamic("/indicator/*", "/", 200);
addDynamic("/place/*", "/", 200);

const header = [
  "# Cloudflare Pages, project smart-city-thailand-index.",
  "# Generated by scripts/write-cf-redirects.mjs. Do not hand-edit the city lines.",
  "# Static rules first (cap 2,000). Wildcards last (cap 100).",
  "# No status-404 rule. A path that is not listed falls through to 404.html.",
  "# `/place/* / 200` rewrites to the root index.",
  "",
];

const lines = [
  ...header,
  ...staticRules,
  "",
  "# Wildcards. These are the only dynamic rules, and they are last.",
  ...dynamicRules,
  "",
];

const out = path.join(root, "public/_redirects");
writeFileSync(out, lines.join("\n"));
const dynamic = dynamicRules.length;
const plain = staticRules.length;
if (dynamic > 100) throw new Error(`${dynamic} dynamic rules, cap is 100`);
if (plain > 2000) throw new Error(`${plain} static rules, cap is 2,000`);
console.log(`wrote ${plain} static and ${dynamic} dynamic rules (${plain + dynamic} total)`);
