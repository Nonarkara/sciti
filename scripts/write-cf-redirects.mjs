// Writes public/_redirects for the Cloudflare Pages project smart-city-thailand-index.
// Static files win first. These rules run only when no file matches.
// Old live URLs are 302s. The app's own routes are rewritten to index.html.
// Anything else falls through to 404.html. There is no catch-all to the shell.

import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { PROVINCE_ALIASES } from "../src/lib/legacy.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const redirects = JSON.parse(readFileSync(path.join(root, "src/data/redirects.json"), "utf8"));
const baseline = JSON.parse(readFileSync(path.join(root, "public/data/baseline.json"), "utf8"));
const byName = new Map(baseline.places.map((place) => [place.en.toLowerCase(), place.id]));

const lines = [
  "# Cloudflare Pages, project smart-city-thailand-index.",
  "# Generated by scripts/write-cf-redirects.mjs. Do not hand-edit the city lines.",
  "# Old pages from https://sciti.nonarkara.org leave the award site behind.",
  "",
  "/creative-economy   /about     302",
  "/bingo               /about     302",
  "/partners            /about     302",
  "/audit               /about     302",
  "/asus                /about     302",
  "/why                 /about     302",
  "/showcase            /about     302",
  "/invest              /about     302",
  "/program             /about     302",
  "/knowledge           /about     302",
  "/Kimi                /about     302",
  "/kimi                /about     302",
  "/rankings            /          302",
  "/discover            /          302",
  "/story               /          302",
  "/map                 /          302",
  "/methodology         /methods   302",
  "/sources             /methods   302",
  "/references          /methods   302",
  "/data/cities.json    /data/baseline.json   302",
  "/downloads/SCITI-2026-cities-dataset.csv   /data/baseline.csv   302",
  "/sitemap.xml         /          302",
  "",
  "# The old Pages Functions served invented city composites. This upload has no Functions.",
  "/api/*               /api-gone.json   404",
  "/api                 /api-gone.json   404",
  "",
];

const slugs = Object.keys(redirects).sort();
for (const slug of slugs) {
  const key = String(redirects[slug]).toLowerCase();
  const id = byName.get(PROVINCE_ALIASES[key] || key);
  if (!id) throw new Error(`no province id for ${slug} → ${redirects[slug]}`);
  lines.push(`/city/${slug}   /place/${id}   302`);
  lines.push(`/canvas/${slug}   /place/${id}   302`);
}
lines.push("/city/*     /   302");
lines.push("/canvas/*   /   302");
lines.push("");
lines.push("# This app's own routes. Unknown paths are not listed, so they 404.");
lines.push("/about            /index.html   200");
lines.push("/compare          /index.html   200");
lines.push("/coverage         /index.html   200");
lines.push("/methods          /index.html   200");
lines.push("/methods/*        /index.html   200");
lines.push("/indicator/*      /index.html   200");
lines.push("/place/*          /index.html   200");
lines.push("");

const out = path.join(root, "public/_redirects");
writeFileSync(out, lines.join("\n"));
console.log(`wrote ${lines.length} lines to ${out}`);
